@contextmanager
def _clock(moment):
    """projects ставит даты по _now: проект «создаётся» в момент генерации."""
    real = projects._now
    projects._now = lambda: moment.isoformat()
    try:
        yield
    finally:
        projects._now = real


def _round(value, step=5_000):
    return max(step, int(round(value / step)) * step)


def clean():
    """Удаляет сгенерированных рекрутёров и всё, что они завели. Возвращает
    Counter: recruiters, specializations, projects, vacancies, invitations, companies."""
    ids = set()
    for path in users.USERS_DIR.glob("*.json"):
        if json.loads(path.read_text(encoding="utf-8")).get("seed") == SEED_MARK:
            ids.add(path.stem)
            path.unlink()
    for user_id in ids:
        (user_names.USER_NAMES_DIR / f"{user_id}.json").unlink(missing_ok=True)
    removed = Counter(recruiters=len(ids))
    for folder, field, what in ((specializations.SPECIALIZATIONS_DIR, "user_id", "specializations"),
                                (projects.PROJECTS_DIR, "user_id", "projects"),
                                (projects.VACANCIES_DIR, "user_id", "vacancies"),
                                (invitations.INVITATIONS_DIR, "recruiter_id", "invitations")):
        for path in folder.glob("*.json"):
            if json.loads(path.read_text(encoding="utf-8")).get(field) in ids:
                path.unlink()
                removed[what] += 1
    used = {p.get("company_id") for p in projects._read_dir(projects.PROJECTS_DIR)}
    for path in projects.COMPANIES_DIR.glob("*.json"):
        if json.loads(path.read_text(encoding="utf-8")).get("created_by") in ids and path.stem not in used:
            path.unlink()
            removed["companies"] += 1
    return removed


class Generator:
    def __init__(self, seed, now):
        # Своё зерно: с тем же числом, что у seed_applicants, идентификаторы не совпадут.
        self.rng = random.Random(f"{SEED_MARK}:{seed}")
        self.now = now
        self.password_hash = users.hash_password(PASSWORD)  # один хеш на всех: 600 000 итераций — это долго
        self.taken = {str(json.loads(p.read_text(encoding="utf-8")).get("email", "")).casefold()
                      for p in users.USERS_DIR.glob("*.json")}
        self.catalog = projects.Catalog()
        self.rules = self.catalog.questionnaire["rules"]
        self.buttons = self._grade_buttons()
        self.stats = Counter()

    @staticmethod
    def _grade_buttons():
        """Грейд → элементы ручного выбора на странице 6: вопрос и кнопка грейда."""
        rows = {r["id"]: r for r in json.loads(specializations.SCHEME.read_text(encoding="utf-8"))}
        found = {}
        for row in sorted(rows.values(), key=lambda r: r["id"]):
            question = rows.get(row.get("anchor_point_id"))
            if (row.get("additional action") == specializations.SELECT_ACTION and question
                    and specializations.PAGE_SPECIALIZATIONS.get(row.get("page")) == specializations.RECRUITER):
                found.setdefault(row["title"].strip(), (row["page"], [
                    {"id": question["id"], "title": question["title"].strip()},
                    {"id": row["id"], "title": row["title"].strip()},
                ]))
        return found

    def _between(self, start, low, high):
        """Момент через [low, high] минут после start; не позже чем за 10 минут до запуска,
        но и не раньше start."""
        moment = start + timedelta(minutes=self.rng.uniform(low, high))
        limit = self.now - timedelta(minutes=10)
        if moment > limit:
            moment = start + max(limit - start, timedelta(0)) * self.rng.uniform(0.5, 1)
        return moment + timedelta(seconds=self.rng.random())

    def recruiter(self):
        """Пользователь-рекрутёр: users, user_specializations, user_names. (id, когда назвался)."""
        rng = self.rng
        user_id = _uuid(rng)
        female = rng.random() < FEMALE_SHARE
        first = rng.choice(FEMALE_NAMES if female else MALE_NAMES)
        last = rng.choice(SURNAMES)
        last = _female_surname(last) if female else last
        _write(users.USERS_DIR / f"{user_id}.json", {
            "id": user_id, "email": _email(rng, first, last, self.taken),
            "password_hash": self.password_hash, "seed": SEED_MARK,
        })
        registered = self.now - timedelta(days=DAYS * rng.random() ** 1.3 + 3, hours=rng.random() * 24)
        chosen = self._between(registered, 1, 15)
        grade = _pick(rng, {g: w for g, w in GRADE_WEIGHTS.items() if g in self.buttons})
        page, elements = self.buttons[grade]
        record = {"id": _uuid(rng), "user_id": user_id, "specialization": specializations.RECRUITER,
                  "grade": grade, "created_at": chosen.isoformat(),
                  "source": {"type": "Manual", "page": page, "elements": elements}}
        _write(specializations.SPECIALIZATIONS_DIR / f"{record['id']}.json", record)
        named = self._between(chosen, 2, 60)
        _write(user_names.USER_NAMES_DIR / f"{user_id}.json", {
            "user_id": user_id, "first_name": first, "last_name": last, "created_at": named.isoformat(),
        })
        self.stats["recruiters"] += 1
        return user_id, named

    def _company(self, entry, user_id, moment):
        """Компания из COMPANIES: та, что уже есть с таким названием, или новая."""
        name = " ".join(entry["name"].split()).casefold()
        for record in projects._read_dir(projects.COMPANIES_DIR):
            if " ".join((record.get("name") or "").split()).casefold() == name:
                return record["id"]
        record = {"id": _uuid(self.rng), "name": entry["name"], "industry": entry["industry"],
                  "city": entry["city"], "description": entry["description"],
                  "created_at": moment.isoformat(), "created_by": user_id}
        projects._write(projects.COMPANIES_DIR / f"{record['id']}.json", record, create=True)
        self.stats["companies"] += 1
        return record["id"]

    def _stack(self, idea):
        """Стек действующей системы: {kind: [id]} по важности, язык бэкенда и фронтенда, брокер, API."""
        rng = self.rng
        extras = set(idea.get("extras", ()))
        if idea.get("onec"):
            integrations = ["rest"] + ["soap"] * ("soap" in extras) + ["file_exchange"] * ("files" in extras)
            return {"languages": ["bsl", "sql"], "databases": [rng.choice(("mssql", "postgresql"))],
                    "integrations": integrations, "backend": "bsl", "frontend": None, "api": "rest", "broker": None}
        backend = rng.choice(idea["backend"])
        domestic = "domestic" in extras
        database = (rng.choice(("postgres_pro", "postgres_pro", "ydb")) if domestic
                    else _pick(rng, {"postgresql": 60, "mysql": 12, "mssql": 10 if backend == "csharp" else 2,
                                     "mongodb": 8}))
        databases = [database]
        if rng.random() < 0.45:
            databases.append("tarantool" if domestic and rng.random() < 0.3 else "redis")
        if "analytics" in extras:
            databases.append("clickhouse")
        if "search" in extras:
            databases.append("elasticsearch")
        api = "graphql" if rng.random() < 0.15 and "web" in idea["clients"] else "rest"
        broker = rng.choice(("kafka", "kafka", "rabbitmq")) if "events" in extras else None
        integrations = [api] + [broker] * bool(broker)
        if "bot" in idea["clients"]:
            extras.add("webhook")  # анкета спрашивает, как бот получает сообщения мессенджера
        for hint, item in (("grpc", "grpc"), ("realtime", "websocket"), ("sso", "oidc"), ("soap", "soap"),
                           ("webhook", "webhook"), ("files", "file_exchange")):
            if hint in extras:
                integrations.append(item)
        frontend = None
        if "web" in idea["clients"]:
            frontend = "typescript" if rng.random() < 0.85 else "javascript"
        languages = [backend] + [frontend] * bool(frontend and frontend != backend)
        for platform in MOBILE.get(idea.get("mobile"), {}).values():
            if platform[1] not in languages:
                languages.append(platform[1])
        if any(self.catalog.items["databases"][d]["model"] in ("relational", "columnar") for d in databases):
            languages.append("sql")
        return {"languages": languages, "databases": databases, "integrations": integrations,
                "backend": backend, "frontend": frontend, "api": api, "broker": broker}

    def _qa_tools(self, idea, stack):
        """Инструменты тестирования действующей системы и есть ли автотесты."""
        rng = self.rng
        tools = ["test_design"]
        automated = not idea.get("onec") and rng.random() < P_AUTOMATION
        if not automated:
            tools += ["exploratory"] + ["postman"] * (rng.random() < 0.4) + ["test_it"] * (rng.random() < 0.3)
            return tools, False
        tools.append({"python": "pytest", "java": "rest_assured", "kotlin": "rest_assured"}.get(
            stack["backend"], rng.choice(("postman", "pytest"))))
        if stack["frontend"]:
            tools.append(_pick(rng, {"playwright": 60, "cypress": 25, "selenium": 15}))
        if idea.get("mobile"):
            tools.append("appium")
        if idea.get("load") == "high" or "load" in idea.get("qa_focus", ()):
            tools.append(_pick(rng, {"k6": 45, "jmeter": 35, "locust": 20}))
        if "data" in idea.get("qa_focus", ()) or rng.random() < 0.15:
            tools.append("sql_checks")
        for tool, chance in (("allure", 0.3), ("exploratory", 0.3), ("testcontainers", 0.15)):
            if rng.random() < chance and tool not in tools:
                tools.append(tool)
        return list(dict.fromkeys(tools)), True

    def _requirement(self, kind, ids, importance, grade, reason, origin="fixed"):
        degrees = self.rules["default_min_degree"]
        return {"kind": kind, "ids": ids, "match": "any" if len(ids) > 1 else "all", "importance": importance,
                "min_degree": degrees["required"][grade] if importance == "required" else degrees["plus"],
                "origin": origin, "reasons": [reason]}

    def _requirements(self, position, grade, stack, tools):
        """Требования вакансии: компетенции стека, которые проверяются у роли (rules.role_scope)."""
        role = self.catalog.positions[position]["role"]
        code, tests = "Код действующей системы", "Тесты действующей системы"
        rows = []
        if role == "backend":
            rows.append(self._requirement("languages", [stack["backend"]], "required", grade, code))
            if "sql" in stack["languages"]:
                rows.append(self._requirement("languages", ["sql"], "plus", grade,
                                              "В стеке реляционная или аналитическая СУБД", "rule"))
            rows += [self._requirement("databases", [d], "required" if n == 0 else "plus", grade, code)
                     for n, d in enumerate(stack["databases"])]
            rows += [self._requirement("integrations", [i], "required" if n < 2 else "plus", grade, code)
                     for n, i in enumerate(stack["integrations"])]
        elif role == "frontend":
            language = stack["frontend"] if position == "frontend_web" else next(
                p[1] for p in MOBILE[stack["mobile"]].values() if p[0] == position)
            rows.append(self._requirement("languages", [language], "required", grade, code))
            allowed = self.rules["role_scope"]["only"]["frontend"]["integrations"]
            rows += [self._requirement("integrations", [i], "required" if i == stack["api"] else "plus", grade, code)
                     for i in stack["integrations"] if i in allowed]
        elif role == "qa":
            used = {lang for tool in tools for lang in self.catalog.items["testing"][tool]["languages"]}
            qa_languages = [lang for lang in self.catalog.items["languages"]
                            if "qa" in self.catalog.items["languages"][lang]["roles"] and lang in used]
            mine = [lang for lang in qa_languages if lang in stack["languages"]] or qa_languages
            if mine:
                rows.append(self._requirement("languages", mine, "required", grade, "Язык автотестов проекта", "rule"))
            rows += [self._requirement("testing", [t], "required" if n < 3 else "plus", grade, tests)
                     for n, t in enumerate(tools)]
        else:
            if "sql" in stack["languages"]:
                rows.append(self._requirement("languages", ["sql"], "required", grade,
                                              "В стеке реляционная или аналитическая СУБД", "rule"))
            rows += [self._requirement("databases", [d], "required" if n == 0 else "plus", grade, code)
                     for n, d in enumerate(stack["databases"][:2])]
            rows += [self._requirement("integrations", [i], "required" if n == 0 else "plus", grade, code)
                     for n, i in enumerate(stack["integrations"][:3])]
        return [row for row in rows if all(self.catalog.in_scope(role, row["kind"], i) for i in row["ids"])]

    def _positions(self, idea, stack):
        """[(позиция, название позиции, название вакансии без грейда)] проекта."""
        rng = self.rng
        found = []
        if idea.get("onec"):
            found.append(("backend_1c", None, "1С-разработчик"))
        else:
            found.append(("backend_main", None, f"{BACKEND_LANGUAGE_NAMES[stack['backend']]}-разработчик"))
        if stack["frontend"]:
            found.append(("frontend_web", None, "Фронтенд-разработчик"))
        variant = idea.get("mobile")
        for platform, (position, _, title) in MOBILE.get(variant, {}).items():
            if platform == "mobile" or platform in idea["clients"]:
                name = (self.catalog.positions[position]["name"].replace(
                    "{mobile_variant_name}", next(v["name"] for v in self.rules["mobile_variants"] if v["id"] == variant))
                    if position == "frontend_mobile" else None)
                found.append((position, name, title))
        if rng.random() < P_QA:
            found.append(("qa", None, "Тестировщик"))
        if rng.random() < P_ANALYST:
            found.append(("analyst", None, "Системный аналитик"))
        return found

    def _text(self, templates, idea, stack, tools, position):
        rng = self.rng
        first, second = rng.sample(idea["features"], 2)
        names = lambda kind, ids: " и ".join(self.catalog.name(kind, i) for i in ids)
        code = [t for t in tools if self.catalog.items["testing"][t]["languages"]]
        named_tools = code or [t for t in tools if t not in ("test_design", "exploratory")] or ["postman"]
        language = stack["frontend"] if position == "frontend_web" else stack["backend"]
        values = {"f1": first, "f2": second, "lang": names("languages", [language]),
                  "db": names("databases", stack["databases"][:1]), "api": names("integrations", [stack["api"]]),
                  "tools": names("testing", named_tools[:2]), "app": MOBILE_APP.get(position, "")}
        return rng.choice(templates).format(**values)

    def _vacancies(self, idea, company, stack, tools, automated, work_format):
        rng = self.rng
        vacancies = []
        for position, position_name, title in self._positions(idea, stack):
            role = self.catalog.positions[position]["role"]
            grades = [_pick(rng, VACANCY_GRADES)]
            if rng.random() < P_SECOND_GRADE[role]:
                grades.append(_pick(rng, {g: w for g, w in VACANCY_GRADES.items() if g != grades[0]}))
            for grade in sorted(grades, key=projects.GRADES.index):
                key = ("onec" if position == "backend_1c" else "backend" if role == "backend"
                       else "frontend_web" if position == "frontend_web" else "mobile" if role == "frontend"
                       else ("qa" if automated else "qa_manual") if role == "qa" else "analyst")
                specialization = self.catalog.roles[role]["specialization"]
                low, high = SALARY[specialization][grade]
                pay = INDUSTRY_PAY[company["industry"]] * (
                    1 if work_format == "remote" else CITY_PAY.get(company["city"], 0.92)) * rng.uniform(0.93, 1.07)
                if position == "backend_1c":
                    pay *= 0.9
                salary_from = _round(low * pay)
                salary_to = max(salary_from + 20_000, _round(salary_from + (high - low) * pay * rng.uniform(0.8, 1.1)))
                assignments = []
                if rng.random() < P_ASSIGNMENT:
                    pool = ASSIGNMENTS["qa" if key == "qa_manual" else key]
                    assignments = [self._text((text,), idea, stack, tools, position)
                                   for text in rng.sample(pool, rng.randint(1, len(pool)))]
                notes = [rng.choice(NOTES)] * (rng.random() < P_NOTES) + [REMOTE_NOTE] * (work_format == "remote")
                if position == "qa" and automated and grade != "Junior":
                    title = "QA-инженер по автоматизации"
                elif position == "qa":
                    title = "Тестировщик"
                vacancies.append({
                    "title": f"{title} ({grade})", "position": position, "position_name": position_name,
                    "grade": grade, "count": 2 if grade == "Middle" and role in ("backend", "frontend")
                    and rng.random() < P_TWO_PEOPLE else 1,
                    "task": self._text(TASKS[key][grade], idea, stack, tools, position),
                    "requirements": self._requirements(position, grade, stack, tools),
                    "assignments": assignments,
                    "salary": {"from": salary_from, "to": salary_to},
                    "notes": " ".join(notes) or None,
                })
        return vacancies

    def _payload(self, company, company_id, idea, created):
        """Ответы и сводка в формате обычной анкеты действующей системы, вакансии."""
        rng = self.rng
        stack = self._stack(idea)
        stack["mobile"] = idea.get("mobile")
        tools, automated = self._qa_tools(idea, stack)
        work_format = _pick(rng, {"office": 20, "hybrid": 35, "remote": 45})
        vacancies = self._vacancies(idea, company, stack, tools, automated, work_format)
        fixed = {}
        for vacancy in vacancies:
            for row in vacancy["requirements"]:
                if row["origin"] == "fixed":
                    item = fixed.setdefault((row["kind"], row["ids"][0]), {
                        "kind": row["kind"], "id": row["ids"][0], "positions": [], "reasons": row["reasons"]})
                    if vacancy["position"] not in item["positions"]:
                        item["positions"].append(vacancy["position"])
        team_plan = {}
        for vacancy in vacancies:
            team_plan.setdefault(vacancy["position"], {})[vacancy["grade"]] = vacancy["count"]
        roles = sorted({self.catalog.positions[v["position"]]["role"] for v in vacancies})
        answers = {
            "project_summary": idea["summary"], "domain": company["industry"],
            "stage": _pick(rng, {"active": 75, "support": 25}),
            "duration": _pick(rng, {"3to6": 20, "6to12": 35, "gt12": 45}),
            "start_date": (created + timedelta(days=rng.randint(10, 60))).date().isoformat(),
            "work_format": work_format, "clients": list(idea["clients"]),
            "stack_limits": ["domestic"] if "domestic" in idea.get("extras", ()) else ["none"],
            "existing_stack": {kind: [i for k, i in fixed if k == kind] for kind in ("languages", "databases", "integrations")},
            "existing_tests": {"testing": [i for k, i in fixed if k == "testing"]},
            "current_team": {role: {_pick(rng, VACANCY_GRADES): rng.randint(1, 3)} for role in roles},
            "knowledge_holder": "yes", "load": idea.get("load", "medium"),
            "third_party_api": "yes" if "partners" in idea.get("extras", ()) else "no",
            "qa_mode": "own_qa", "qa_automation": "auto" if automated else "manual",
            "qa_focus": list(idea.get("qa_focus", ("logic",))),
            "requirements_state": _pick(rng, {"ready": 30, "partial": 50, "idea": 20}),
            "team_plan": team_plan,
        }
        if work_format != "remote":
            answers["city"] = company["city"]
        if idea.get("mobile"):
            answers["mobile_native"] = "native" if idea["mobile"] == "native" else "cross"
        if idea.get("onec"):
            answers["host_platform"] = "onec"
        for item in fixed.values():
            key = f"fixed_details[{item['kind']}:{item['id']}]"
            answers[f"{key}.positions"] = item["positions"]
            answers[f"{key}.importance"] = "required"
            answers[f"{key}.depth"] = "by_grade"
        for vacancy in vacancies:
            key = f"vacancies[{vacancy['position']}:{vacancy['grade']}]"
            for field in ("title", "task", "requirements", "assignments", "salary", "notes"):
                answers[f"{key}.{field}"] = vacancy[field]
        positions = list(dict.fromkeys(v["position"] for v in vacancies))
        summary = {
            "stack_mode": "fixed", "kind_mode": {kind: "fixed" for kind in self.catalog.items},
            "mobile_variant": idea.get("mobile"),
            "positions": [{"id": p, "role": self.catalog.positions[p]["role"],
                           "name": next(v["position_name"] for v in vacancies if v["position"] == p)
                           or self.catalog.positions[p]["name"]} for p in positions],
            "fixed_stack": list(fixed.values()), "choices": [], "team_plan": team_plan, "open_questions": [],
        }
        return {"name": idea["name"], "company": {"id": company_id}, "answers": answers,
                "summary": summary, "vacancies": vacancies}

    def project(self, user_id, company, idea, after):
        """Проект с утверждёнными вакансиями; часть — с завершённым набором. Когда создан."""
        rng = self.rng
        created = self._between(after, 30, 7 * 1440)
        company_id = self._company(company, user_id, created)
        payload = self._payload(company, company_id, idea, created)
        with _clock(created):
            view = projects.create(user_id, payload)
        approved = self._between(created, 10, 3 * 1440)
        with _clock(approved):
            view = projects.approve(user_id, view["id"], payload["vacancies"], [])
        self.stats["projects"] += 1
        self.stats["vacancies"] += len(view["vacancies_list"])
        self.stats["people"] += sum(v["count"] for v in view["vacancies_list"])
        completed = approved + timedelta(days=rng.uniform(5, 30))
        if rng.random() < P_COMPLETED and completed < self.now:
            with _clock(completed):
                projects.set_completed(user_id, view["id"], True)
            self.stats["completed"] += 1
        else:
            self.stats["open_vacancies"] += len(view["vacancies_list"])
        return created

    def report(self):
        s = self.stats
        print(f"Рекрутёров: {s['recruiters']}; новых компаний {s['companies']}, проектов {s['projects']} "
              f"(набор завершён — {s['completed']}), вакансий {s['vacancies']} на {s['people']} человек, "
              f"открыто для соискателей {s['open_vacancies']}.")


def generate(count, seed, now=None):
    """Генерирует count рекрутёров и раздаёт им проекты из COMPANIES: каждому хотя бы
    один, остальные — случайным. Рекрутёров больше, чем проектов, — лишние без проектов."""
    generator = Generator(seed, now or datetime.now(timezone.utc))
    recruiters = [generator.recruiter() for _ in range(count)]
    ideas = [(company, idea) for company in COMPANIES for idea in company["projects"]]
    generator.rng.shuffle(ideas)
    last = {}
    for index, (company, idea) in enumerate(ideas):
        if not recruiters:
            break
        user_id, named = recruiters[index] if index < len(recruiters) else generator.rng.choice(recruiters)
        last[user_id] = generator.project(user_id, company, idea, last.get(user_id, named))
    return generator


def main():
    parser = argparse.ArgumentParser(description="Генерирует рекрутёров с проектами и вакансиями для демонстрации")
    parser.add_argument("--count", type=int, default=COUNT)
    parser.add_argument("--seed", type=int, default=2026)
    parser.add_argument("--clean", action="store_true", help="только удалить сгенерированных")
    args = parser.parse_args()
    sys.stdout.reconfigure(encoding="utf-8")
    removed = clean()
    if removed["recruiters"]:
        print(f"Удалены сгенерированные прошлым запуском: рекрутёров {removed['recruiters']}, проектов "
              f"{removed['projects']}, вакансий {removed['vacancies']}, приглашений {removed['invitations']}, "
              f"компаний {removed['companies']}")
    if args.clean:
        return
    generate(args.count, args.seed).report()


if __name__ == "__main__":
    main()
